"""A case-scoped Python analysis tool for TrajStory tasks."""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path
from typing import Any, Dict, Optional

import numpy as np
import pandas as pd
from pydantic import Field

from src.registry import TOOL
from src.tool.default_tools.executor import LocalPythonExecutor
from src.tool.types import Tool, ToolResponse


_DESCRIPTION = """Execute Python analysis against one sanitised TrajStory case.

The case specification is generated by examples/run_trajstory.py and never
contains gold insights.  The execution namespace provides:
- `df`: a copy of the primary table;
- `tables`: a dict of all pandas DataFrames keyed by names from the case spec;
- `case`: the sanitised case metadata;
- `pd` and `np` for general-purpose Python data analysis.

Print compact numerical evidence.  Do not merely describe a calculation.

Args:
- spec_path (str): absolute path to the sanitised case_input.json.
- code (str): Python code to execute in the case-scoped namespace.
"""


@TOOL.register_module(force=True)
class TrajstoryAnalysisTool(Tool):
    """Execute bounded, reproducible analysis with all case tables preloaded."""

    name: str = "trajstory_analysis"
    description: str = _DESCRIPTION
    metadata: Dict[str, Any] = Field(default_factory=dict)
    require_grad: bool = False
    trajstory_root: Optional[str] = None
    max_output_chars: int = 50_000
    use_trajstory_helpers: bool = True

    def __init__(
        self,
        trajstory_root: Optional[str] = None,
        max_output_chars: int = 50_000,
        use_trajstory_helpers: bool = True,
        require_grad: bool = False,
        **kwargs: Any,
    ) -> None:
        super().__init__(require_grad=require_grad, **kwargs)
        self.trajstory_root = str(Path(trajstory_root).resolve()) if trajstory_root else None
        self.max_output_chars = max_output_chars
        # Keep historical controlled runs reproducible. The minimal config
        # explicitly disables these task-specific analysis functions.
        self.use_trajstory_helpers = use_trajstory_helpers

    def _inside_root(self, path: Path) -> bool:
        if self.trajstory_root is None:
            return True
        try:
            path.relative_to(Path(self.trajstory_root))
            return True
        except ValueError:
            return False

    def _load_helpers(self) -> dict[str, Any]:
        if self.trajstory_root is None:
            return {}
        module_path = Path(self.trajstory_root) / "baseline_support" / "analysis_tools.py"
        if not module_path.is_file():
            return {}
        spec = importlib.util.spec_from_file_location("trajstory_shared_analysis_tools", module_path)
        if spec is None or spec.loader is None:
            return {}
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        names = (
            "parse_timestamps",
            "haversine_km",
            "point_to_polyline_haversine_km",
            "assign_trajectories_to_routes",
            "match_events_to_trajectory_points",
            "map_categories",
            "add_normalized_progress",
            "trajectory_features",
            "grouped_summary",
            "safe_merge",
            "correlation_table",
            "statistic",
            "table_from_frame",
        )
        return {name: getattr(module, name) for name in names if hasattr(module, name)}

    async def __call__(self, spec_path: str, code: str, **kwargs: Any) -> ToolResponse:
        try:
            path = Path(spec_path).resolve()
            if not path.is_file():
                raise FileNotFoundError(f"Case specification does not exist: {path}")
            if not self._inside_root(path):
                raise ValueError(f"Case specification is outside trajstory_root: {path}")

            case = json.loads(path.read_text(encoding="utf-8"))
            forbidden = {"insight_list", "insights", "summary"}.intersection(case)
            if forbidden:
                raise ValueError(f"Case specification contains forbidden gold fields: {sorted(forbidden)}")
            if case.get("format") != "trajstory-agent-input-v1":
                raise ValueError("Unsupported or unsanitised TrajStory case specification")

            tables: dict[str, pd.DataFrame] = {}
            for table in case.get("tables") or []:
                table_path = Path(table["path"]).resolve()
                if not self._inside_root(table_path):
                    raise ValueError(f"Input table is outside trajstory_root: {table_path}")
                tables[table["name"]] = pd.read_csv(table_path, low_memory=False)
            if "main" not in tables:
                raise ValueError("Case specification has no main table")

            helpers = self._load_helpers() if self.use_trajstory_helpers else {}
            executor = LocalPythonExecutor(
                additional_authorized_imports=[
                    "pandas",
                    "numpy",
                    "matplotlib",
                    "matplotlib.pyplot",
                    "seaborn",
                    "scipy",
                    "sklearn",
                    "json",
                    "math",
                    "statistics",
                ],
                max_print_outputs_length=self.max_output_chars,
            )
            executor.send_variables(
                {
                    "case": case,
                    "tables": tables,
                    "df": tables["main"].copy(),
                    "pd": pd,
                    "np": np,
                }
            )
            executor.send_tools(helpers)
            output = executor(code)
            message = f"Stdout:\n{output.logs}\nOutput:\n{output.output}"
            if len(message) > self.max_output_chars:
                message = message[: self.max_output_chars] + "\n...[output truncated]"
            return ToolResponse(success=True, message=message)
        except Exception as exc:
            return ToolResponse(success=False, message=f"TrajStory analysis error: {exc}")
